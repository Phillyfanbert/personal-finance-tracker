#!/usr/bin/env node
// Puts records back from a daily backup (tools/backup-database.mjs).
//
// Two modes, and the safe one is the default:
//
//   node restore-backup.mjs FILE
//       CHECK ONLY. Opens the file, checks every table in it (the count it
//       claims, a primary key on every row, no key twice, records that point
//       at rows the file does not hold) and says what it holds. Touches no
//       database and needs no key. Run this first, every time.
//
//   node restore-backup.mjs FILE --into URL [--user ID] [--table a,b] [--production]
//       PUTS BACK WHAT IS MISSING, and nothing else: a row whose key is already
//       there is left exactly as it is, never changed and never deleted. So it
//       can be run against a database that lost only some of its rows, and run
//       twice without doing anything the second time.
//
// What that means in practice, which is the reason this is never one command
// against the real database:
//   - Rows deleted ON PURPOSE since the backup was made come back. Restoring a
//     week-old copy brings back every expense deleted that week.
//   - A balance row (an account, an asset, a debt) that is missing comes back
//     with its figure from the day of the backup, not today's.
//   - Nothing is merged. A row that exists but is wrong stays wrong.
// --user ID limits it to one person's rows, which is the usual case: one
// household member's records went wrong and nobody else's should be touched.
// --table limits it to the tables named.
//
// The target: --into is the project's URL. The key is RESTORE_SERVICE_ROLE_KEY,
// or, only when --into is the project this repo's env file names, that
// project's own SUPABASE_SERVICE_ROLE_KEY. Writing into the project the backup
// CAME FROM, or the one the env file names, also needs --production: the real
// database is the one place a mistake here costs real records.
//
// Order matters, because rows point at each other: an asset before the account
// linked to it, an account before its expenses, a purchase before the money
// back on it (the refund cap in 89 checks the purchase), a holding's account
// before the holding. The order comes from the target's own description of its
// foreign keys, with the known ones built in as a floor, so a table added later
// is ordered without anyone listing it here.
//
// Not restorable through this tool:
//   - record_history. Its id is generated by the database and the server key
//     may only read and delete it (88), which is what keeps it append-only. If
//     it is ever needed back, that is SQL editor work.
//   - Sign-in accounts. They live in Supabase Auth, not in the backup. Every
//     row belongs to one, so a person with no sign-in account in the target
//     has every row refused, and the summary says so. Into a NEW project, each
//     person's sign-in has to exist with their old id first.
//
// Rows go in 500 at a time. If a batch is refused, its rows are tried one by
// one so a single bad row (a second Cash account, a person with no sign-in)
// is named instead of taking 499 good ones down with it. Exit status: 0 done,
// 1 failed, 2 refused to start, 3 done with some rows refused.

import { readFileSync, existsSync, realpathSync } from "node:fs";
import { gunzipSync } from "node:zlib";
import { fileURLToPath } from "node:url";

const ENV_FILE = new URL("./.env.deal-agent", import.meta.url);
if (existsSync(ENV_FILE)) {
  for (const line of readFileSync(ENV_FILE, "utf8").split("\n")) {
    const m = line.match(/^\s*(?:export\s+)?([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (!m) continue;
    const value = m[2].replace(/^(['"])(.*)\1$/, "$2");
    if (!(m[1] in process.env)) process.env[m[1]] = value;
  }
}

const CHUNK = 500;
// Never written through the API; see the header.
const NOT_RESTORABLE = { record_history: "only its own trigger writes it, so it is SQL editor work" };
// The foreign keys between public tables as of 91. The target's description
// adds any newer ones; these hold even if it describes none.
const KNOWN_FKS = {
  accounts: { linked_asset_id: "assets", linked_liability_id: "liabilities" },
  assets: { parent_asset_id: "assets" },
  expenses: { account_id: "accounts", refund_of: "expenses" },
  subscriptions: { account_id: "accounts", pays_liability_id: "liabilities" },
  income: { account_id: "accounts" },
  account_activity: { account_id: "accounts", related_account_id: "accounts", liability_id: "liabilities", asset_id: "assets" },
  holding_sales: { asset_id: "assets", account_id: "accounts" },
};

const args = process.argv.slice(2);
const flag = (name) => args.includes(name);
const option = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};
const FILE = args.find((a, i) => !a.startsWith("--") && !["--into", "--user", "--table"].includes(args[i - 1]));

function stop(code, msg) {
  console.error(msg);
  process.exit(code);
}

function readBackup(path) {
  if (!path || !existsSync(path)) stop(2, `No backup file at ${path || "(none given)"}.\nUsage: node restore-backup.mjs FILE [--into URL] [--user ID] [--table a,b] [--production]`);
  let raw = readFileSync(path);
  if (raw[0] === 0x1f && raw[1] === 0x8b) raw = gunzipSync(raw);
  let data;
  try { data = JSON.parse(raw.toString("utf8")); } catch (err) { stop(1, `The file is not readable as a backup: ${err.message}`); }
  if (data?.format !== 1 || !data.tables || typeof data.tables !== "object") stop(1, "The file is not a backup this tool understands (expected format 1).");
  return data;
}

const keyOf = (row, pk) => JSON.stringify(pk.map((c) => row[c]));

// Everything wrong with the file itself, as messages. A table whose rows do
// not add up to its own count, or that holds one key twice, cannot be trusted
// to restore cleanly, so those are problems; a record pointing at a row the
// file does not hold is only noted, because the tables are read one after
// another and a row deleted in between leaves exactly that.
export function checkBackup(data) {
  const problems = [];
  const notes = [];
  const ids = {};
  for (const [name, t] of Object.entries(data.tables)) {
    const rows = Array.isArray(t.rows) ? t.rows : null;
    const pk = Array.isArray(t.primary_key) && t.primary_key.length ? t.primary_key : ["id"];
    if (!rows) { problems.push(`${name}: no rows list`); continue; }
    if (t.count !== rows.length) problems.push(`${name}: says ${t.count} rows, holds ${rows.length}`);
    const seen = new Set();
    let missingKey = 0;
    let twice = 0;
    for (const r of rows) {
      if (pk.some((c) => r[c] == null)) { missingKey++; continue; }
      const k = keyOf(r, pk);
      if (seen.has(k)) twice++;
      seen.add(k);
    }
    if (missingKey) problems.push(`${name}: ${missingKey} rows have no ${pk.join("+")}`);
    if (twice) problems.push(`${name}: ${twice} rows repeat a ${pk.join("+")} already in the file`);
    if (pk.length === 1 && pk[0] === "id") ids[name] = new Set(rows.map((r) => r.id));
  }
  for (const [name, cols] of Object.entries(KNOWN_FKS)) {
    const rows = data.tables[name]?.rows || [];
    for (const [col, ref] of Object.entries(cols)) {
      if (!ids[ref]) continue;
      const dangling = rows.filter((r) => r[col] != null && !ids[ref].has(r[col])).length;
      if (dangling) notes.push(`${name}.${col}: ${dangling} point at a ${ref} row this file does not hold`);
    }
  }
  return { problems, notes };
}

// Tables in an order where every table comes after the ones it points at.
// A table pointing at itself is handled inside it (rowsInOrder). A loop
// between two tables would have no such order; none exists, and if one ever
// appears the remaining tables go last in name order rather than not at all.
export function tableOrder(names, fks) {
  const pending = new Set(names);
  const order = [];
  while (pending.size) {
    const ready = [...pending].filter((t) => Object.values(fks[t] || {}).every((ref) => ref === t || !pending.has(ref))).sort();
    const next = ready.length ? ready : [...pending].sort();
    for (const t of next) { order.push(t); pending.delete(t); }
    if (!ready.length) break;
  }
  return order;
}

// Rows of a table that points at itself, in batches where each row's parent
// is in an earlier batch (or not being restored at all, so already there or
// genuinely gone).
export function rowsInOrder(rows, selfCols) {
  if (!selfCols.length) return [rows];
  const byId = new Map(rows.map((r) => [r.id, r]));
  const placed = new Set();
  const levels = [];
  let left = rows;
  while (left.length) {
    const level = left.filter((r) => selfCols.every((c) => r[c] == null || !byId.has(r[c]) || placed.has(r[c])));
    if (!level.length) { levels.push(left); break; }
    level.forEach((r) => placed.add(r.id));
    levels.push(level);
    left = left.filter((r) => !placed.has(r.id));
  }
  return levels;
}

function belongsTo(name, row, user) {
  if (name === "profiles") return row.id === user;
  return row.user_id === user;
}

async function main() {
  const data = readBackup(FILE);
  const into = option("--into");
  const user = option("--user");
  const only = option("--table") ? new Set(option("--table").split(",").map((s) => s.trim()).filter(Boolean)) : null;

  const { problems, notes } = checkBackup(data);
  const names = Object.keys(data.tables).sort();
  const total = names.reduce((n, t) => n + data.tables[t].rows.length, 0);
  const people = new Set(names.flatMap((t) => data.tables[t].rows.map((r) => (t === "profiles" ? r.id : r.user_id)).filter(Boolean)));
  console.log(`Backup made ${data.created_at} from ${data.source}: ${names.length} tables, ${total} rows, ${people.size} people.`);
  for (const t of names) console.log(`  ${t.padEnd(24)} ${String(data.tables[t].rows.length).padStart(6)}`);
  for (const n of notes) console.log(`  note: ${n}`);
  if (problems.length) {
    for (const p of problems) console.error(`  PROBLEM: ${p}`);
    stop(1, "This file does not check out, so nothing was restored from it.");
  }
  if (!into) {
    console.log("The file checks out. Nothing was written: add --into URL to restore from it.");
    return;
  }

  // Which database, and whether it is the real one.
  let target;
  try { target = new URL(into); } catch { stop(2, `--into ${into} is not a URL.`); }
  const configured = process.env.SUPABASE_URL ? new URL(process.env.SUPABASE_URL).host : null;
  const isProduction = target.host === data.source || (configured && target.host === configured);
  if (isProduction && !flag("--production")) {
    stop(2, `${target.host} is the real database${target.host === data.source ? " this backup came from" : ""}. Rows deleted on purpose since ${data.created_at.slice(0, 10)} would come back. If that is what you want, run it again with --production${user ? "" : ", and consider --user to touch one person only"}.`);
  }
  const key = process.env.RESTORE_SERVICE_ROLE_KEY || (configured && target.host === configured ? process.env.SUPABASE_SERVICE_ROLE_KEY : null);
  if (!key) stop(2, "No key for that database. Set RESTORE_SERVICE_ROLE_KEY to its service-role key.");
  const base = `${target.origin}/rest/v1`;
  const headers = { apikey: key, Authorization: `Bearer ${key}` };

  async function rest(path, init = {}) {
    const stopper = new AbortController();
    const timer = setTimeout(() => stopper.abort(), 60000);
    try {
      return await fetch(`${base}/${path}`, { ...init, signal: stopper.signal, headers: { ...headers, ...(init.headers || {}) } });
    } finally {
      clearTimeout(timer);
    }
  }

  // What the target says it has: its tables, their columns, and the foreign
  // keys between them.
  const res = await rest("", { headers: { Accept: "application/openapi+json" } });
  if (!res.ok) stop(1, `Could not read what ${target.host} holds (HTTP ${res.status}), so nothing was written.`);
  const defs = (await res.json()).definitions || {};
  const fks = {};
  for (const [t, cols] of Object.entries(KNOWN_FKS)) fks[t] = { ...cols };
  for (const [t, def] of Object.entries(defs)) {
    for (const [col, prop] of Object.entries(def.properties || {})) {
      const m = (prop.description || "").match(/<fk table='([^']+)' column='[^']+'\/>/);
      if (m) (fks[t] ||= {})[col] = m[1];
    }
  }

  const chosen = names.filter((t) => !only || only.has(t));
  if (only) for (const t of only) if (!data.tables[t]) console.log(`  ${t}: not in this backup`);
  const order = tableOrder(chosen, fks);
  console.log(`\nRestoring into ${target.host}${user ? `, rows of ${user} only` : ""}. Rows already there are left as they are.`);

  // Before anything is written: a column the target does not have cannot be
  // put back, and quietly leaving it out changes what a row means (a refund
  // without refund_of is just a negative expense). A column that is empty in
  // every row loses nothing and is left out; one holding data stops the
  // restore here, with nothing written.
  const lost = [];
  for (const name of order) {
    if (NOT_RESTORABLE[name] || !defs[name]) continue;
    const known = new Set(Object.keys(defs[name].properties || {}));
    const cols = new Set(data.tables[name].rows.flatMap((r) => Object.keys(r).filter((k) => !known.has(k) && r[k] != null)));
    if (cols.size) lost.push(`${name}: ${[...cols].join(", ")}`);
  }
  if (lost.length) {
    for (const l of lost) console.error(`  the target has no column for: ${l}`);
    stop(1, "Restoring would lose what those columns hold, so nothing was written. Check the target is on the same version of the app as the backup.");
  }

  const summary = [];
  let refusedTotal = 0;
  for (const name of order) {
    const t = data.tables[name];
    if (NOT_RESTORABLE[name]) { summary.push([name, `skipped: ${NOT_RESTORABLE[name]}`]); continue; }
    if (!defs[name]) { summary.push([name, "skipped: the target has no such table"]); continue; }
    let rows = t.rows;
    if (user) {
      if (name !== "profiles" && !rows.some((r) => "user_id" in r)) { summary.push([name, "skipped: belongs to nobody, and --user was given"]); continue; }
      rows = rows.filter((r) => belongsTo(name, r, user));
    }
    if (!rows.length) { summary.push([name, "nothing to restore"]); continue; }

    // Only columns empty in every row can be missing by now (checked above);
    // they are left out, and a column the target has gained takes its default.
    const known = new Set(Object.keys(defs[name].properties || {}));
    const dropped = new Set();
    const clean = rows.map((r) => {
      const out = {};
      for (const [k, v] of Object.entries(r)) { if (known.has(k)) out[k] = v; else dropped.add(k); }
      return out;
    });
    const pk = t.primary_key?.length ? t.primary_key : ["id"];
    const selfCols = Object.entries(fks[name] || {}).filter(([, ref]) => ref === name).map(([c]) => c);
    const query = `${encodeURIComponent(name)}?on_conflict=${pk.join(",")}&select=${pk.join(",")}`;
    const post = (body) => rest(query, {
      method: "POST",
      headers: { "Content-Type": "application/json", Prefer: "resolution=ignore-duplicates,return=representation" },
      body: JSON.stringify(body),
    });

    let added = 0;
    const refused = [];
    for (const level of rowsInOrder(clean, selfCols)) {
      for (let i = 0; i < level.length; i += CHUNK) {
        const batch = level.slice(i, i + CHUNK);
        const r = await post(batch);
        if (r.ok) { added += (await r.json()).length; continue; }
        // One at a time, so the bad row is named and the good ones still go in.
        for (const row of batch) {
          const one = await post([row]);
          if (one.ok) { added += (await one.json()).length; continue; }
          const why = await one.json().catch(() => ({}));
          refused.push({ key: pk.map((c) => row[c]).join("+"), why: [why.code, why.message].filter(Boolean).join(" ") || `HTTP ${one.status}` });
        }
      }
    }
    refusedTotal += refused.length;
    const already = rows.length - added - refused.length;
    summary.push([name, `${added} put back, ${already} already there${refused.length ? `, ${refused.length} refused` : ""}${dropped.size ? ` (left out empty columns the target does not have: ${[...dropped].join(", ")})` : ""}`]);
    for (const x of refused.slice(0, 20)) console.log(`  refused ${name} ${x.key}: ${x.why}`);
    if (refused.length > 20) console.log(`  ... and ${refused.length - 20} more refused in ${name}`);
  }

  console.log("");
  for (const [name, line] of summary) console.log(`  ${name.padEnd(24)} ${line}`);
  if (refusedTotal) {
    console.log(`\n${refusedTotal} rows were refused; their reasons are above. Everything else is back.`);
    process.exit(3);
  }
  console.log("\nDone. Run the balance check (reconcile_balances) to see that the books add up.");
}

// Run as a command, or imported by the tests for its pure parts. Compared as
// REAL paths: on macOS /tmp is a link to /private/tmp, and comparing the two
// spellings decided it was not being run at all, so it exited 0 having done
// nothing, which is the one thing a restore check must never do.
const runAsCommand = (() => {
  try { return !!process.argv[1] && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url)); } catch { return false; }
})();
if (runAsCommand) {
  main().catch((err) => stop(1, `Restore failed: ${err.message}. Rows already put back stay; running it again puts back the rest.`));
}
